#!/usr/bin/env python3
"""The staff's symbols for THEORY-1 (app/staff_glyphs.h), from Bravura (Steinberg, SIL OFL 1.1: LICENSES/):

    npm pack @vexflow-fonts/bravura@1.0.2 && tar xzf vexflow-fonts-bravura-1.0.2.tgz
    python3 app/tools/make_glyphs.py package/bravura.otf

Bravura is a SMuFL font: an em is four staff spaces, and a glyph's baseline is the line it belongs on (a G clef's,
the G line; a notehead's, its middle). At 32 px a staff space is 8 pixels, the screen's. Each glyph becomes a 4-bit
coverage bitmap with its offset from that baseline point."""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

GLYPHS = [("G_CLEF", 0xE050), ("F_CLEF", 0xE062), ("C_CLEF", 0xE05C), ("HEAD", 0xE0A4), ("SHARP", 0xE262),
          ("FLAT", 0xE260)]
SIZE = 32


def main():
    font = ImageFont.truetype(sys.argv[1], SIZE)
    out = ["/* SPDX-License-Identifier: OFL-1.1", " * Generated by app/tools/make_glyphs.py from Bravura (Copyright (c) 2019,",
           " * Steinberg Media Technologies GmbH; SIL Open Font License 1.1, LICENSES/OFL-1.1-Bravura.txt): the staff's",
           " * symbols at 8 pixels a staff space, 4-bit coverage, two pixels a byte (high nibble first). */",
           "#pragma once", "#include <stdint.h>", "typedef struct {", "    int8_t dx, dy;      /* the bitmap's top left, from the baseline point */",
           "    uint8_t w, h;", "    const uint8_t *data;", "} sglyph_t;", ""]
    for name, cp in GLYPHS:
        im = Image.new("L", (200, 200), 0)
        ox, oy = 60, 120
        ImageDraw.Draw(im).text((ox, oy), chr(cp), font=font, fill=255, anchor="ls")
        x0, y0, x1, y1 = im.getbbox()
        w, h = x1 - x0, y1 - y0
        px = im.load()
        data = []
        for y in range(y0, y1):
            row = [px[x, y] * 15 // 255 for x in range(x0, x1)]
            if w % 2:
                row.append(0)
            data += [row[i] << 4 | row[i + 1] for i in range(0, len(row), 2)]
        out.append(f"static const uint8_t SG_{name}_DATA[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 24]) + ",")
        out.append("};")
        out.append(f"static const sglyph_t SG_{name} = {{{x0 - ox}, {y0 - oy}, {w}, {h}, SG_{name}_DATA}};")
        out.append("")
        print(f"{name}: {w}x{h} at ({x0 - ox}, {y0 - oy})")
    (Path(__file__).resolve().parent.parent / "staff_glyphs.h").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
